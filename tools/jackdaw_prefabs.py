#!/usr/bin/env python3
"""Write the Jackdaw prefabs for the world assets: one `.bsn` per placeable model,
under `jackdaw/assets/prefabs/`, so a level is built by dragging prefabs from the
Project window into the viewport.

Levels are designed with these: every placeable world asset gets one, and a new
asset joins this list in the PR that adds it.

Each prefab names its model with a `GltfSource`, adds a `LodGroup` when the model has
a `<name>_LOD1.glb` beside it, and carries the game component that identifies it in
Play (`MineNode` for a scrub oak, `ResourceNode` and `PulseFollower` for a lightning
bug). Assets whose game component does not exist yet (reeds, the burbler) place as
models; their components arrive with the catalog work in their changes. The game
still has to bind behaviour to placed entities (`add-opening-region` 2.5): until it
does, a placed bug or module shows its model but does not flash or sound.

Placed instances must get their own `instance` ID: the prefab's is only a default.

Reproduce: python3 tools/jackdaw_prefabs.py   (checked by `jackdaw/tests/prefabs.rs`)
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets"
OUT = ROOT / "jackdaw/assets/prefabs"
GAME = "stubby_jackdaw::desert"
HEADER = "// Generated by tools/jackdaw_prefabs.py from {source}. Do not edit by hand.\n"


def lod_group(near, far):
    """Two levels: the model while it covers `near` of the screen's height, the
    `_LOD1` file down to `far`, and nothing below."""
    return (
        "jackdaw_scene_types::types::LodGroup {\n"
        "    levels: [\n"
        f"        jackdaw_scene_types::types::LodLevel {{ screen_height: {near} }},\n"
        f"        jackdaw_scene_types::types::LodLevel {{ screen_height: {far} }},\n"
        "    ],\n"
        "    fade: 0.1,\n"
        "}\n"
    )


def prefab(name, model, source, lod=None, components=()):
    text = HEADER.format(source=source)
    text += f'#"{name}"\n'
    text += "jackdaw::prefab::components::Prefab\n"
    text += "jackdaw::prefab::components::PrefabEntityId(0)\n"
    text += "bevy_transform::components::transform::Transform\n"
    text += "bevy_camera::visibility::Visibility::Visible\n"
    text += f'jackdaw_scene_types::types::GltfSource {{ path: "{model}", scene_index: 0 }}\n'
    if lod:
        text += lod_group(*lod)
    for component in components:
        text += component + "\n"
    return text


def model_path(profile_model):
    return profile_model.split("#")[0]


def main():
    written = {}

    def put(rel, text):
        path = OUT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        written[rel] = text

    oak = json.loads((ASSETS / "flora/scrub_oak/asset.json").read_text())
    for k, model in enumerate(oak["variants"]):
        put(f"flora/scrub_oak_{k}.bsn", prefab(
            f"Scrub oak {k}", model_path(model), "assets/flora/scrub_oak/asset.json",
            lod=(0.07, 0.004),
            components=[f'{GAME}::resources::MineNode {{ mine: "scrub_oak", instance: "scrub_oak-{k}" }}']))

    reeds = json.loads((ASSETS / "flora/reeds/asset.json").read_text())
    for k, model in enumerate(reeds["variants"]):
        put(f"flora/reed_clump_{k}.bsn", prefab(
            f"Reed clump {k}", model_path(model), "assets/flora/reeds/asset.json", lod=(0.045, 0.002)))

    props = json.loads((ASSETS / "props/desert/asset.json").read_text())
    for family, models in props["families"].items():
        for k, model in enumerate(models):
            put(f"props/desert_{family}_{k}.bsn", prefab(
                f"Desert {family} {k}", model_path(model), "assets/props/desert/asset.json"))

    put("creatures/lightning_bug.bsn", prefab(
        "Lightning bug", "models/lightning_bug.glb", "assets/creatures/lightning_bug/asset.json",
        components=[f'{GAME}::resources::ResourceNode {{ resource: "lightning_bug", '
                    f'instance: "lightning_bug-placed-0", collected: false }}',
                    f"{GAME}::pulse::PulseFollower {{ clock: 1 }}"]))

    for module in ("square_vco", "sine_vco", "saw_vco", "triangle_vco", "clock_lamp"):
        title = " ".join(w.upper() if w == "vco" else w.capitalize() for w in module.split("_"))
        put(f"modules/{module}.bsn", prefab(
            title, f"models/{module}.glb", f"assets/modules/{module}/asset.json"))

    put("machines/mudpit_burbler.bsn", prefab(
        "Mudpit burbler", "models/mudpit_burbler.glb", "assets/machines/mudpit_burbler/asset.json"))
    put("streams/stream_segment.bsn", prefab(
        "Stream segment", "models/stream_segment.glb", "assets/streams/stream_segment/asset.json"))

    for stale in OUT.rglob("*.bsn"):   # prefabs whose asset is gone
        if str(stale.relative_to(OUT)) not in written:
            stale.unlink()
    print(f"wrote {len(written)} prefabs under {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
