#!/usr/bin/env python3
"""Keep our Bevy-main forks of third-party crates current (jackdaw/bevy_main_forks.json).

For each fork: start from the published release commit, rewrite every Bevy engine
dependency (`bevy`, `bevy_*` at the configured Bevy minor) to Bevy's git main, commit,
and push the result to the fork's branch when its tree changed. The root Cargo.toml
patches crates.io to these branches; Cargo.lock decides the Bevy revision.

    tools/bevy_main_forks.py ensure    # create forks/branches as needed and push
    tools/bevy_main_forks.py patch     # print the [patch.crates-io] block
"""
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / 'jackdaw/bevy_main_forks.json'
WORK = Path(os.environ.get('BEVY_MAIN_FORKS_DIR', ROOT.parent / 'forks'))
BEVY_GIT = 'git = "https://github.com/bevyengine/bevy", branch = "main"'
MESSAGE = 'Build against Bevy main\n\nGenerated by stubby-music tools/bevy_main_forks.py: Bevy engine\ndependencies point at https://github.com/bevyengine/bevy main.'


def run(*args, cwd=None, capture=False):
    result = subprocess.run(args, cwd=cwd, check=True, text=True,
                            stdout=subprocess.PIPE if capture else None)
    return result.stdout.strip() if capture else None


def port_manifest(text, minor):
    version = r'"\^?' + re.escape(minor) + r'(?:\.\d+)?"'
    text = re.sub(r'(?m)^(bevy(?:_[a-z_]+)?)\s*=\s*\{\s*version\s*=\s*' + version,
                  r'\1 = { ' + BEVY_GIT, text)
    return re.sub(r'(?m)^(bevy(?:_[a-z_]+)?)\s*=\s*' + version + r'\s*$',
                  r'\1 = { ' + BEVY_GIT + ' }', text)


def ensure(config):
    for fork in config['forks']:
        owner_repo = fork['fork'].removeprefix('https://github.com/')
        name = owner_repo.split('/')[1]
        if subprocess.run(['gh', 'repo', 'view', owner_repo], capture_output=True).returncode:
            upstream = fork['upstream'].removeprefix('https://github.com/')
            run('gh', 'repo', 'fork', upstream, '--clone=false', '--default-branch-only')
        path = WORK / name
        if not path.exists():
            WORK.mkdir(parents=True, exist_ok=True)
            run('git', 'clone', '-q', fork['upstream'], str(path))
        run('git', 'remote', 'set-url', 'origin', fork['upstream'], cwd=path)
        if subprocess.run(['git', 'remote', 'get-url', 'fork'], cwd=path, capture_output=True).returncode:
            run('git', 'remote', 'add', 'fork', fork['fork'] + '.git', cwd=path)
        run('git', 'fetch', '-q', '--tags', 'origin', cwd=path)
        subprocess.run(['git', 'fetch', '-q', 'fork'], cwd=path)
        run('git', 'checkout', '-q', '-f', '-B', config['branch'], fork['base'], cwd=path)
        changed = []
        for manifest in run('git', 'ls-files', '*Cargo.toml', cwd=path, capture=True).splitlines():
            file = path / manifest
            text = file.read_text()
            ported = port_manifest(text, config['bevy_minor'])
            if ported != text:
                file.write_text(ported)
                changed.append(manifest)
        if not changed:
            sys.exit(f"{name}: no Bevy {config['bevy_minor']} dependencies to port; check the config")
        run('git', 'add', *changed, cwd=path)
        run('git', '-c', 'commit.gpgsign=false', 'commit', '-q', '-m', MESSAGE, cwd=path)
        remote = f"fork/{config['branch']}"
        has_remote = not subprocess.run(['git', 'rev-parse', '-q', '--verify', remote], cwd=path,
                                        capture_output=True).returncode
        same = has_remote and not subprocess.run(['git', 'diff', '--quiet', remote, 'HEAD'], cwd=path).returncode \
            and run('git', 'rev-parse', f'{remote}^', cwd=path, capture=True) == run('git', 'rev-parse', 'HEAD^', cwd=path, capture=True)
        if same:
            print(f"{name}: {config['branch']} is current")
            continue
        # The branch is generated from the release; replacing it is intended.
        run('git', 'push', '-q', '--force', 'fork', f"HEAD:refs/heads/{config['branch']}", cwd=path)
        print(f"{name}: pushed {config['branch']} ({', '.join(changed)})")


def patch(config):
    lines = ['[patch.crates-io]']
    for fork in config['forks']:
        lines.append(f'{fork["crate"]} = {{ git = "{fork["fork"]}", branch = "{config["branch"]}" }}')
    return '\n'.join(lines)


def main():
    config = json.loads(CONFIG.read_text())
    command = sys.argv[1] if len(sys.argv) > 1 else 'ensure'
    if command == 'ensure':
        ensure(config)
    elif command == 'patch':
        print(patch(config))
    else:
        sys.exit(__doc__)


if __name__ == '__main__':
    main()
